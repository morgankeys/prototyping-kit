// Turns the shared Docs reader into the model every platform target consumes.
import { readGuidelines, readTokens, defaultMode, kebab } from "../../export-design-md/scripts/read-docs.mjs";

export const MARKER = "GENERATED by design-system-export from Docs/Design system. Do not edit.";
export const PROMPT_LIMIT = 10000;

const FOUNDATION = {
  color: "foundations/color.md",
  typography: "foundations/typography.md",
  layout: "foundations/layout.md",
};

export function systemName() {
  return { name: "Design system", slug: "design-system" };
}

export function buildModel(repoRoot, components) {
  const warnings = [];
  const guidelines = readGuidelines(repoRoot);
  const tokens = readTokens(repoRoot, (message) => warnings.push(message));
  const modeNames = new Set();
  for (const token of tokens) if (token.modes) for (const mode of Object.keys(token.modes)) modeNames.add(mode);
  const mode = modeNames.size ? defaultMode(modeNames) : null;
  const { name, slug } = systemName();
  return {
    name,
    slug,
    guidelines,
    tokens,
    components,
    modeNames: [...modeNames],
    defaultMode: mode,
    tokensCss: tokensCss({ name, tokens, modeNames: [...modeNames], defaultMode: mode }),
    warnings,
  };
}

export function tokensCss(model) {
  const lines = [
    `/* ${MARKER}`,
    "   Values come from Docs/Design system token JSON.",
  ];
  if (model.defaultMode) {
    lines.push(`   Default mode ${model.defaultMode} is on :root.`);
    lines.push('   Other modes use :root[data-mode="<id>"], with the id taken from the token source.');
  }
  lines.push(" */", ":root {");
  for (const token of model.tokens) {
    if (token.description) lines.push(`  /* ${token.description.replace(/\*\//g, "")} */`);
    lines.push(`  --${token.name}: ${token.modes ? token.modes[model.defaultMode] ?? Object.values(token.modes)[0] : token.css};`);
  }
  lines.push("}");
  for (const mode of model.modeNames.filter((name) => name !== model.defaultMode)) {
    const body = model.tokens
      .filter((token) => token.modes && token.modes[mode] != null)
      .map((token) => `  --${token.name}: ${token.modes[mode]};`);
    if (!body.length) continue;
    lines.push("", `:root[data-mode="${kebab([mode])}"] {`, ...body, "}");
  }
  lines.push("");
  return lines.join("\n");
}

function portable(text) {
  return text
    .split("\n")
    .filter((line) => !/(^|[\s`(])(Code|Agents|Docs)\//.test(line))
    .join("\n")
    .trim();
}

export function guidelineFolder(model) {
  const files = {};
  const shape = [];
  const routes = [];
  for (const guide of model.guidelines) {
    const body = portable(guide.content);
    if (!body) continue;
    if (guide.id === "shape" || guide.id === "elevation") {
      shape.push(`# ${guide.title}\n\n${body}`);
      continue;
    }
    const path = FOUNDATION[guide.id] ?? `foundations/${guide.id}.md`;
    files[path] = `# ${guide.title}\n\n${body}\n`;
    routes.push([`Choosing ${guide.title.toLowerCase()}`, path]);
  }
  if (shape.length) {
    files["foundations/shape-and-elevation.md"] = `${shape.join("\n\n")}\n`;
    routes.push(["Corner radius, elevation, or shadows", "foundations/shape-and-elevation.md"]);
  }
  for (const component of model.components) {
    const path = `components/${kebab([component.name])}.md`;
    const props = component.props.length
      ? `\n\n| Prop | Values |\n| --- | --- |\n${component.props.map((prop) => `| \`${prop.name}\` | ${(prop.values ?? []).join(", ")} |`).join("\n")}\n`
      : "";
    files[path] = `# ${component.name}\n\n${component.summary || "Use the shipped component."}${props}\n\nKeep its class names and data attributes. Do not restyle it with hardcoded colors, sizes, or radii.\n`;
    routes.push([`Using ${component.name}`, path]);
  }

  const setup = [
    `# Setup`,
    "",
    "Import the generated `tokens.css` once, before any component CSS. It defines the system's custom properties. Use those variables for every color, font setting, radius, and spacing value.",
  ];
  if (model.defaultMode) {
    setup.push("", `The default mode is \`${model.defaultMode}\` and applies with no attribute. Set \`data-mode\` on the root element to one of: ${model.modeNames.map((name) => `\`${kebab([name])}\``).join(", ")}.`);
  }
  files["setup.md"] = `${setup.join("\n")}\n`;
  routes.unshift(["Starting a project or importing styles", "setup.md"]);

  const table = routes.map(([when, path]) => `| ${when} | \`${path}\` |`).join("\n");
  files["Guidelines.md"] = `# ${model.name}\n\n${MARKER}\n\nRead \`setup.md\` before writing any code, then the file for whatever you are styling.\n\n| When you are… | Read |\n| --- | --- |\n${table}\n`;
  return files;
}

export function tokenTable(model) {
  const lines = ["| Token | Value |", "| --- | --- |"];
  for (const token of model.tokens) {
    const value = token.modes
      ? Object.entries(token.modes).map(([mode, css]) => `${mode}: ${css}`).join("; ")
      : token.css;
    lines.push(`| \`--${token.name}\` | ${value.replace(/\|/g, "\\|")} |`);
  }
  return lines.join("\n");
}

export function instructions(model) {
  const parts = [
    `# ${model.name}`,
    "",
    MARKER,
    "",
    "Use this design system for every screen. Take colors, type, spacing, radius, and elevation from the custom properties in tokens.css. Do not hardcode those values.",
  ];
  for (const guide of model.guidelines) {
    const body = portable(guide.content);
    if (body) parts.push("", `## ${guide.title}`, "", body);
  }
  if (model.tokens.length) parts.push("", "## Tokens", "", tokenTable(model));
  if (model.components.length) {
    parts.push("", "## Components", "");
    for (const component of model.components) {
      parts.push(`- ${component.name}${component.summary ? `: ${component.summary}` : ""}`);
    }
  }
  return `${parts.join("\n").trim()}\n`;
}

export function assertPromptLimit(label, text) {
  if (text.length > PROMPT_LIMIT) {
    throw new Error(`${label} is ${text.length} characters. The platform limit is 10,000. Shorten the guidelines and re-run.`);
  }
}

export function libraryFiles(model) {
  if (!model.components.length) return null;
  const files = {
    "package.json": `${JSON.stringify({
      name: model.slug,
      version: "0.0.0",
      private: true,
      type: "module",
      exports: {
        ".": "./src/index.ts",
        "./tokens.css": "./src/styles/tokens.css",
      },
      peerDependencies: { react: ">=18" },
    }, null, 2)}\n`,
    "src/styles/tokens.css": model.tokensCss,
    "src/index.ts": `${model.components.map((component) => `export { default as ${component.name} } from "./components/${component.file.replace(/\.tsx$/, "")}";`).join("\n")}\n`,
  };
  for (const component of model.components) {
    files[`src/components/${component.file}`] = component.code.endsWith("\n") ? component.code : `${component.code}\n`;
    if (component.css) files[`src/components/${component.cssFile}`] = component.css.endsWith("\n") ? component.css : `${component.css}\n`;
  }
  return files;
}
