// The deviations backlog: regenerated on every run, `Rationale:` lines carried forward
// by file + rule + detail (contract: "The backlog and its rationale contract" in
// Docs/Design system/design-in-code architecture.md).
import fs from 'node:fs';
import path from 'node:path';

export const SENTINEL = 'Unknown — needs review';

const FILE_HEADING = /^### `(.+)`\s*$/;
const ENTRY = /^- \*\*L(\d+) · ([a-z0-9-]+)\*\* — (.*)$/;
const RATIONALE = /^ {2}- Rationale:\s?(.*)$/;
const CONTINUATION = /^ {4}(\S.*)$/;

const key = (file, rule, detail) => `${file}\u0000${rule}\u0000${detail}`;

// Map of key -> list of rationale texts (several entries can share a key).
export function readRationale(text) {
  const out = new Map();
  let file = null;
  let current = null;
  for (const line of text.split('\n')) {
    const heading = FILE_HEADING.exec(line);
    if (heading) {
      file = heading[1];
      current = null;
      continue;
    }
    const entry = ENTRY.exec(line);
    if (entry && file) {
      current = { key: key(file, entry[2], entry[3]), lines: null };
      continue;
    }
    const rationale = RATIONALE.exec(line);
    if (rationale && current && current.lines === null) {
      current.lines = [rationale[1]];
      if (!out.has(current.key)) out.set(current.key, []);
      out.get(current.key).push(current.lines);
      continue;
    }
    const cont = CONTINUATION.exec(line);
    if (cont && current?.lines) {
      current.lines.push(cont[1]);
      continue;
    }
    if (line.trim() === '') continue;
    current = null;
  }
  return new Map([...out].map(([k, list]) => [k, list.map((l) => l.join('\n'))]));
}

export function renderBacklog(deviations, previous = new Map()) {
  const pools = new Map([...previous].map(([k, v]) => [k, [...v]]));
  const byFile = new Map();
  for (const d of deviations) {
    if (!byFile.has(d.file)) byFile.set(d.file, []);
    byFile.get(d.file).push(d);
  }
  const counts = new Map();
  for (const d of deviations) counts.set(d.rule, (counts.get(d.rule) ?? 0) + 1);

  const lines = [
    '<!-- GENERATED by `validate`. Do not edit by hand, except the `Rationale:` lines, which are carried forward. -->',
    '',
    '# Design-system deviations backlog',
    '',
    'Every place the code departs from the design system, rewritten on each run of `validate`.',
    'Write why on each `Rationale:` line; see "Working a deviation" in',
    '`Docs/Design system/design-in-code architecture.md`.',
    '',
  ];
  if (!deviations.length) {
    lines.push('No deviations.', '');
    return lines.join('\n');
  }
  lines.push(`${deviations.length} deviation${deviations.length === 1 ? '' : 's'}.`, '', '| Rule | Count |', '| --- | --- |');
  for (const [rule, n] of [...counts].sort(([a], [b]) => a.localeCompare(b))) lines.push(`| \`${rule}\` | ${n} |`);
  lines.push('');

  for (const file of [...byFile.keys()].sort()) {
    lines.push(`### \`${file}\``, '');
    const entries = byFile.get(file).sort((a, b) => a.line - b.line || a.rule.localeCompare(b.rule) || a.detail.localeCompare(b.detail));
    for (const d of entries) {
      const k = key(file, d.rule, d.detail);
      const pool = pools.get(k);
      const rationale = pool?.length > 1 ? pool.shift() : pool?.[0] ?? SENTINEL;
      const [first, ...rest] = rationale.split('\n');
      lines.push(`- **L${d.line} · ${d.rule}** — ${d.detail}`, `  - Rationale: ${first}`);
      for (const r of rest) lines.push(`    ${r}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

// Returns true when the file changed.
export function writeBacklog(file, deviations) {
  const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const next = renderBacklog(deviations, readRationale(previous));
  if (next === previous) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, next);
  return true;
}
