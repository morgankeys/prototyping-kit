#!/usr/bin/env node
// design-md.mjs — helpers for the export-design-md skill. No dependencies beyond Node 18+.
//
//   node Agents/skills/export-design-md/scripts/design-md.mjs collect
//     Prints one Markdown bundle of everything the export draws on: the filled-in parts of
//     Docs/Design system/Guidelines/ (stub placeholders, comments, and repo-specific
//     sections stripped) and a flat digest of every token in Figma/Tokens/unpacked/ and
//     Supplemental/. Exits 3 when there is nothing to export yet.
//
//   node Agents/skills/export-design-md/scripts/design-md.mjs lint [file]
//     Runs Google's DESIGN.md linter (pinned below) on Export/DESIGN.md or [file], then the
//     kit's own checks. Exits non-zero on any error.

import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LINTER = "@google/design.md@0.4.0";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const DS = join(ROOT, "Docs/Design system");
const GUIDELINES = join(DS, "Guidelines");
const TOKEN_DIRS = [join(DS, "Figma/Tokens/unpacked"), join(DS, "Supplemental")];
const OUTPUT = join(ROOT, "Export/DESIGN.md");
export const MARKER = "GENERATED by /export-design-md";

// Guideline files in DESIGN.md section order. components.md is left out on purpose: the
// portable export carries no components. Any other topic file is appended after these.
const ORDER = [
  "overview", "color", "typography", "layout", "elevation", "shape",
  "motion", "accessibility", "content",
];
const SKIP_FILES = new Set(["README.md", "_template.md", "components.md"]);
// Sections that only make sense inside this repo.
const SKIP_SECTIONS = new Set(["sources", "open questions"]);

const rel = (p) => relative(ROOT, p);

function walk(dir, ext) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return walk(p, ext);
    return p.endsWith(ext) ? [p] : [];
  });
}

// --- Guidelines --------------------------------------------------------------------------

const isPlaceholder = (line) =>
  line.includes("…") || /<[A-Za-z][^>]*>/.test(line) || /^\s*-\s*\*\*(Do|Don't)\*\*\s*$/.test(line);

function cleanGuideline(text) {
  const body = text
    .replace(/^---\n[\s\S]*?\n---\n/, "")
    .replace(/<!--[\s\S]*?-->/g, "");
  const sections = [];
  let current = { heading: null, lines: [] };
  for (const line of body.split("\n")) {
    if (/^#{1,6}\s/.test(line)) {
      sections.push(current);
      current = { heading: line, lines: [] };
    } else {
      current.lines.push(line);
    }
  }
  sections.push(current);

  const kept = [];
  for (const { heading, lines } of sections) {
    if (!heading || heading.startsWith("# ")) continue; // title; the bundle supplies its own
    const name = heading.replace(/^#+\s*/, "").trim().toLowerCase();
    if (SKIP_SECTIONS.has(name)) continue;
    const out = [];
    let table = [];
    const flushTable = () => {
      if (table.length > 2) out.push(...table); // header + separator alone means unfilled
      table = [];
    };
    for (const line of lines) {
      if (line.trim().startsWith("|")) {
        if (!isPlaceholder(line)) table.push(line);
        continue;
      }
      flushTable();
      if (!isPlaceholder(line)) out.push(line);
    }
    flushTable();
    const content = out.join("\n").trim();
    if (content) kept.push(`${heading.replace(/^##/, "###")}\n\n${content}`);
  }
  return kept.join("\n\n");
}

function guidelineFiles() {
  const all = existsSync(GUIDELINES)
    ? readdirSync(GUIDELINES).filter((f) => f.endsWith(".md") && !SKIP_FILES.has(f))
    : [];
  const ordered = ORDER.map((t) => `${t}.md`).filter((f) => all.includes(f));
  return [...ordered, ...all.filter((f) => !ordered.includes(f)).sort()];
}

// --- Tokens ------------------------------------------------------------------------------

const hex2 = (n) => Math.round(n * 255).toString(16).padStart(2, "0").toUpperCase();

// Figma stores opacity in `alpha`; `hex` is RGB only. Keep the alpha (AGENTS.md rule 6).
function colorValue(v) {
  if (typeof v === "string") return v;
  const alpha = v.alpha ?? 1;
  let rgb = v.hex?.slice(0, 7).toUpperCase();
  if (!rgb && v.components) {
    const c = Array.isArray(v.components)
      ? v.components
      : [v.components.red, v.components.green, v.components.blue];
    rgb = `#${c.map(hex2).join("")}`;
  }
  return alpha < 1 ? `${rgb}${hex2(alpha)}` : rgb;
}

function flattenTokens(node, path, out) {
  if (node && typeof node === "object" && "$value" in node) {
    const type = node.$type ?? "";
    const value = type === "color" ? colorValue(node.$value) : node.$value;
    out.push({ path: path.join("."), type, value: typeof value === "object" ? JSON.stringify(value) : String(value) });
    return;
  }
  if (!node || typeof node !== "object") return;
  for (const [key, child] of Object.entries(node)) {
    if (!key.startsWith("$")) flattenTokens(child, [...path, key], out);
  }
}

function tokenGroups() {
  return TOKEN_DIRS.flatMap((dir) => walk(dir, ".json")).flatMap((file) => {
    const tokens = [];
    try {
      flattenTokens(JSON.parse(readFileSync(file, "utf8")), [], tokens);
    } catch (err) {
      console.error(`warning: skipped ${rel(file)}: ${err.message}`);
    }
    return tokens.length ? [{ file, tokens }] : [];
  });
}

// --- Commands ----------------------------------------------------------------------------

function collect() {
  const sha = (() => {
    try { return execFileSync("git", ["-C", ROOT, "rev-parse", "--short", "HEAD"], { stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); }
    catch { return "unknown"; }
  })();
  const date = new Date().toISOString().slice(0, 10);
  const parts = [
    "# DESIGN.md export bundle",
    "",
    `Write to: \`${rel(OUTPUT)}\``,
    `Marker line (put right after the front matter): \`<!-- ${MARKER} from Docs/Design system/ @ ${sha} on ${date}. Do not edit by hand; edit the sources and re-export. -->\``,
  ];

  const filled = [];
  const empty = [];
  const guidelineParts = [];
  for (const f of guidelineFiles()) {
    const content = cleanGuideline(readFileSync(join(GUIDELINES, f), "utf8"));
    if (content) {
      filled.push(f);
      guidelineParts.push(`## Guideline: ${f}\n\n${content}`);
    } else {
      empty.push(f);
    }
  }
  const groups = tokenGroups();
  const tokenCount = groups.reduce((n, g) => n + g.tokens.length, 0);

  parts.push(
    "",
    `Filled guidelines: ${filled.join(", ") || "none"}`,
    `Unfilled (omit their sections): ${empty.join(", ") || "none"}`,
    `Tokens: ${tokenCount} in ${groups.length} file(s)`,
    "",
    ...guidelineParts.flatMap((p) => [p, ""]),
  );
  for (const { file, tokens } of groups) {
    parts.push(`## Tokens: ${rel(file)}`, "", "| Path | Type | Value |", "| --- | --- | --- |");
    for (const t of tokens) parts.push(`| ${t.path} | ${t.type} | ${t.value.replace(/\|/g, "\\|")} |`);
    parts.push("");
  }
  console.log(parts.join("\n"));

  if (!filled.length && !tokenCount) {
    console.error("Nothing to export yet: every guideline is a stub and there are no tokens.");
    process.exit(3);
  }
}

function lint(file = OUTPUT) {
  const path = resolve(file);
  if (!existsSync(path)) {
    console.error(`No file at ${rel(path)}. Run the export first.`);
    process.exit(2);
  }
  const result = spawnSync("npx", ["--yes", LINTER, "lint", path], { stdio: "inherit" });
  if (result.error) {
    console.error(`Could not run ${LINTER}: ${result.error.message}`);
    process.exit(2);
  }

  const text = readFileSync(path, "utf8");
  const problems = [];
  if (!text.includes(MARKER)) problems.push(`missing the "${MARKER}" marker comment`);
  if (/^##\s+Components\s*$/m.test(text)) problems.push("has a Components section; the portable export leaves components out");
  if (/`(Code|Agents|Docs)\//.test(text)) problems.push("mentions repo paths; the portable export must stand alone");
  for (const p of problems) console.error(`kit check: ${p}`);

  process.exit(result.status || (problems.length ? 1 : 0));
}

const [command, arg] = process.argv.slice(2);
if (command === "collect") collect();
else if (command === "lint") lint(arg);
else {
  console.error("usage: design-md.mjs collect | lint [file]");
  process.exit(2);
}
